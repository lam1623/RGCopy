export type Lang = "en" | "es";
const dictionaries: Record<Lang, Record<TranslationKey, string>> = { en, es };

export function resolveLang(setting: string | undefined): Lang {
  if (setting === "es" || setting === "en") return setting;
  return navigator.language?.toLowerCase().startsWith("es") ? "es" : "en";
}

export function translate(lang: Lang, key: TranslationKey, vars?: Record<string, string | number>): string {
  const template = dictionaries[lang][key] ?? en[key] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? `{${name}}`));
}

export function hasKey(key: string): key is TranslationKey {
  return key in en;
}

export function useLang(): Lang {
  const setting = useStore((s) => s.settings?.language);
  return resolveLang(setting);
}

export type Translator = (key: TranslationKey, vars?: Record<string, string | number>) => string;

export function useT(): Translator {
  const lang = useLang();
  return useCallback((key, vars) => translate(lang, key, vars), [lang]);
}
